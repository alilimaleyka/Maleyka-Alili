public class Tapsiriq1 {
    public static void main(String[] args) {

        //1-dən 10-a qədər olan ədədləri hər birini yeni sətirdə çap et. do-while dövrəsi istifadə olunmalıdır.

        int i = 1;
        do {
            System.out.println(i);
            i++;
        } while (i <= 10);
    }
}
